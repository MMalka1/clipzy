_clean = re.compile(r"[^\w-]+", re.UNICODE)


def emoji_for(text: str) -> str | None:
    word = _clean.sub("", text.lower())
    if len(word) < 3:
        return None
    for stem, emo in STEMS:
        if word.startswith(stem):
            return emo
    return None


def phrase_emoji(words: list[str]) -> str | None:
    for w in words:
        e = emoji_for(w)
        if e:
            return e
    return None
